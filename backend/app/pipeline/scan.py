class ScannedFile(BaseModel):
    path: str
    language: Language
    size: int
    lines: int


class SkippedFile(BaseModel):
    path: str
    reason: SkipReason


class EntryHint(BaseModel):
    kind: str = Field(description="e.g. package_main, npm_script, dockerfile_cmd, pyproject_script")
    file: str
    detail: str


class LanguageStat(BaseModel):
    files: int = 0
    lines: int = 0


class ScanResult(BaseModel):
    root: str
    files: list[ScannedFile]
    skipped: list[SkippedFile]
    skipped_counts: dict[str, int]
    languages: dict[str, LanguageStat]
    frameworks: list[str]
    manifests: list[str]
    entry_hints: list[EntryHint]
    readme_excerpt: str
    tree: str

    @property
    def code_files(self) -> list[ScannedFile]:
        return [f for f in self.files if f.language != "text"]


@dataclass
class ScanLimits:
    max_file_bytes: int = 1_000_000
    max_files: int = 20_000
    max_skipped_listed: int = 300
    readme_chars: int = 1500
    tree_max_lines: int = 400


def detect_language(path: Path) -> Language | None:
    name = path.name.lower()
    ext = path.suffix.lower()
    if ext in EXT_LANGUAGE:
        return EXT_LANGUAGE[ext]
    if ext in TEXT_EXTS or name in TEXT_NAMES or name.startswith("dockerfile"):
        return "text"
    if ext == "" and name in TEXT_NAMES:
        return "text"
    return None


def _looks_binary(sample: bytes) -> bool:
    return b"\x00" in sample


def _looks_minified(sample: bytes) -> bool:
    lines = sample.split(b"\n")
    if len(lines) <= 1 and len(sample) > 2000:
        return True
    longest = max((len(line) for line in lines), default=0)
    return longest > 1500


def _looks_generated(rel: str, sample: bytes) -> bool:
    if any(p.search(rel) for p in GENERATED_PATTERNS):
        return True
    head = sample[:600]
    return any(marker in head for marker in GENERATED_MARKERS)


class _IgnoreStack:
    """Collects .gitignore files while walking so nested ignores apply to their subtree."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.specs: list[tuple[str, pathspec.GitIgnoreSpec]] = []
        self._load(root, "")

    def _load(self, directory: Path, prefix: str) -> None:
        gi = directory / ".gitignore"
        if gi.is_file():
            try:
                lines = gi.read_text(encoding="utf-8", errors="ignore").splitlines()
            except OSError:
                return
            self.specs.append((prefix, pathspec.GitIgnoreSpec.from_lines(lines)))

    def enter(self, directory: Path, prefix: str) -> None:
        self._load(directory, prefix)

    def ignored(self, rel: str, *, is_dir: bool) -> bool:
        probe = rel + "/" if is_dir else rel
        for prefix, spec in self.specs:
            if prefix and not rel.startswith(prefix):
                continue
            sub = probe[len(prefix) :] if prefix else probe
            if spec.match_file(sub):
                return True
        return False


def _walk(root: Path, ignores: _IgnoreStack) -> Iterator[tuple[Path, str, SkipReason | None]]:
    stack: list[tuple[Path, str]] = [(root, "")]
    while stack:
        directory, prefix = stack.pop()
        try:
            children = sorted(directory.iterdir(), key=lambda p: p.name.lower())
        except OSError:
            continue
        for child in children:
            rel = f"{prefix}{child.name}"
            if child.is_symlink():
                continue
            if child.is_dir():
                if child.name.lower() in SKIP_DIRS:
                    yield child, rel, "ignored_dir"
                    continue
                if ignores.ignored(rel, is_dir=True):
                    yield child, rel, "gitignore"
                    continue
                ignores.enter(child, rel + "/")
                stack.append((child, rel + "/"))
            elif child.is_file():
                yield child, rel, None


MEDIA_EXTS = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".mp3", ".mp4", ".webp", ".ico"}


def _classify_by_name(path: Path) -> Language | SkipReason:
    name = path.name.lower()
    if name in LOCK_FILES:
        return "lock_file"
    ext = path.suffix.lower()
    if ext in BINARY_EXTS:
        return "media" if ext in MEDIA_EXTS else "binary"
    language = detect_language(path)
    return language if language is not None else "binary"


def _sniff(path: Path, rel: str, language: Language, limits: ScanLimits) -> SkipReason | None:
    if path.stat().st_size > limits.max_file_bytes:
        return "too_large"
    with path.open("rb") as fh:
        sample = fh.read(8192)
    if _looks_binary(sample):
        return "binary"
    if language != "text" and _looks_generated(rel, sample):
        return "generated"
    if language != "text" and _looks_minified(sample):
        return "minified"
    return None


def _classify(path: Path, rel: str, limits: ScanLimits) -> tuple[Language, int, int] | SkipReason:
    verdict = _classify_by_name(path)
    if verdict in SKIP_REASONS:
        return verdict  # type: ignore[return-value]
    language: Language = verdict  # type: ignore[assignment]
    try:
        reason = _sniff(path, rel, language, limits)
        if reason is not None:
            return reason
        with path.open("rb") as fh:
            lines = sum(1 for _ in fh)
        return language, path.stat().st_size, lines
    except OSError:
        return "unreadable"


def _read_text(path: Path, limit: int = 200_000) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="ignore")[:limit]
    except OSError:
        return ""


