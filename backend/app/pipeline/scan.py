def _find(by_name: dict[str, str], name: str) -> list[str]:
    return [p for lower, p in by_name.items() if lower == name or lower.endswith("/" + name)]


def _package_json(root: Path, rel: str, frameworks: set[str], hints: list[EntryHint]) -> None:
    try:
        data = json.loads(_read_text(root / rel))
    except json.JSONDecodeError:
        return
    if not isinstance(data, dict):
        return
    deps = {**data.get("dependencies", {}), **data.get("devDependencies", {})}
    frameworks.update(v for k, v in FRAMEWORK_DEPS.items() if k in deps)
    if isinstance(data.get("main"), str):
        hints.append(EntryHint(kind="package_main", file=rel, detail=data["main"]))
    bins = data.get("bin")
    if isinstance(bins, str):
        hints.append(EntryHint(kind="package_bin", file=rel, detail=bins))
    elif isinstance(bins, dict):
        hints.extend(
            EntryHint(kind="package_bin", file=rel, detail=f"{k}: {v}") for k, v in bins.items()
        )
    scripts = data.get("scripts", {})
    for key in ("start", "dev", "serve", "build"):
        if key in scripts:
            hints.append(EntryHint(kind="npm_script", file=rel, detail=f"{key}: {scripts[key]}"))


def _pyproject(root: Path, rel: str, frameworks: set[str], hints: list[EntryHint]) -> None:
    try:
        data = tomllib.loads(_read_text(root / rel))
    except tomllib.TOMLDecodeError:
        return
    project = data.get("project", {})
    poetry = data.get("tool", {}).get("poetry", {}).get("dependencies", {})
    dep_text = " ".join(project.get("dependencies", [])).lower() + " " + " ".join(poetry).lower()
    frameworks.update(
        v for k, v in FRAMEWORK_DEPS.items() if re.search(rf"\b{re.escape(k)}\b", dep_text)
    )
    for name, target in project.get("scripts", {}).items():
        hints.append(EntryHint(kind="pyproject_script", file=rel, detail=f"{name} = {target}"))


def _requirements(root: Path, rel: str, frameworks: set[str], _hints: list[EntryHint]) -> None:
    text = _read_text(root / rel).lower()
    frameworks.update(
        v for k, v in FRAMEWORK_DEPS.items() if re.search(rf"^{re.escape(k)}\b", text, re.M)
    )


def _substring_detector(
    table: dict[str, str], *, quoted: bool = False
) -> Callable[[Path, str, set[str], list[EntryHint]], None]:
    def detect(root: Path, rel: str, frameworks: set[str], _hints: list[EntryHint]) -> None:
        text = _read_text(root / rel)
        for key, label in table.items():
            needles = (f"'{key}'", f'"{key}"') if quoted else (key,)
            if any(n in text for n in needles):
                frameworks.add(label)

    return detect


def _dockerfile(root: Path, rel: str, _frameworks: set[str], hints: list[EntryHint]) -> None:
    for line in _read_text(root / rel).splitlines():
        stripped = line.strip()
        if stripped.upper().startswith(("CMD", "ENTRYPOINT")):
            hints.append(EntryHint(kind="dockerfile_cmd", file=rel, detail=stripped[:200]))


def _procfile(root: Path, rel: str, _frameworks: set[str], hints: list[EntryHint]) -> None:
    for line in _read_text(root / rel).splitlines():
        if ":" in line:
            hints.append(EntryHint(kind="procfile", file=rel, detail=line.strip()[:200]))


def _csproj(root: Path, rel: str, frameworks: set[str], _hints: list[EntryHint]) -> None:
    text = _read_text(root / rel)
    if "Microsoft.AspNetCore" in text or 'Sdk="Microsoft.NET.Sdk.Web"' in text:
        frameworks.add("ASP.NET Core")


MANIFEST_HANDLERS: list[tuple[str, Callable[[Path, str, set[str], list[EntryHint]], None]]] = [
    ("package.json", _package_json),
    ("requirements.txt", _requirements),
    ("pyproject.toml", _pyproject),
    ("go.mod", _substring_detector(GO_FRAMEWORKS)),
    ("cargo.toml", _substring_detector(RUST_FRAMEWORKS)),
    ("gemfile", _substring_detector(RUBY_FRAMEWORKS, quoted=True)),
    ("composer.json", _substring_detector(PHP_FRAMEWORKS)),
    ("pom.xml", _substring_detector(JAVA_MARKERS)),
    ("build.gradle", _substring_detector(JAVA_MARKERS)),
    ("build.gradle.kts", _substring_detector(JAVA_MARKERS)),
    ("procfile", _procfile),
]


def _manifest_info(
    root: Path, files: list[ScannedFile]
) -> tuple[list[str], list[str], list[EntryHint]]:
    frameworks: set[str] = set()
    manifests: list[str] = []
    hints: list[EntryHint] = []
    by_name = {f.path.lower(): f.path for f in files}
    for name, handler in MANIFEST_HANDLERS:
        for rel in _find(by_name, name):
            manifests.append(rel)
            handler(root, rel, frameworks, hints)
    for rel in [p for lower, p in by_name.items() if lower.endswith(".csproj")]:
        manifests.append(rel)
        _csproj(root, rel, frameworks, hints)
    dockerfiles = [
        p for lower, p in by_name.items() if lower.rsplit("/", 1)[-1].startswith("dockerfile")
    ]
    for rel in dockerfiles:
        manifests.append(rel)
        _dockerfile(root, rel, frameworks, hints)
    return sorted(frameworks), sorted(set(manifests)), hints


def _readme_excerpt(root: Path, files: list[ScannedFile], chars: int) -> str:
    candidates = [f.path for f in files if f.path.lower().rsplit("/", 1)[-1].startswith("readme")]
    candidates.sort(key=lambda p: (p.count("/"), len(p)))
    if not candidates:
        return ""
    text = _read_text(root / candidates[0], limit=chars * 4)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)  # drop images
    text = re.sub(r"<[^>]+>", "", text)  # drop html
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return text[:chars]


def build_tree(paths: list[str], max_lines: int) -> str:
    """Compact indented tree; directories with many files are elided."""
    tree: dict[str, dict] = {}  # type: ignore[type-arg]
    for p in paths:
        node = tree
        for part in p.split("/"):
            node = node.setdefault(part, {})
    lines: list[str] = []

    def emit(node: dict, depth: int) -> None:  # type: ignore[type-arg]
        dirs = sorted(k for k, v in node.items() if v)
        files = sorted(k for k, v in node.items() if not v)
        for d in dirs:
            if len(lines) >= max_lines:
                return
            lines.append("  " * depth + d + "/")
            emit(node[d], depth + 1)
        shown = files if len(files) <= 12 else files[:10]
        for f in shown:
            if len(lines) >= max_lines:
                return
            lines.append("  " * depth + f)
        if len(files) > len(shown):
            lines.append("  " * depth + f"… {len(files) - len(shown)} more files")

    emit(tree, 0)
    if len(lines) >= max_lines:
        lines.append("… (tree truncated)")
    return "\n".join(lines)


def scan_project(root: Path, limits: ScanLimits | None = None) -> ScanResult:
    limits = limits or ScanLimits()
    ignores = _IgnoreStack(root)
    files: list[ScannedFile] = []
    skipped: list[SkippedFile] = []
    counts: Counter[str] = Counter()

    def skip(rel: str, reason: SkipReason) -> None:
        counts[reason] += 1
        if len(skipped) < limits.max_skipped_listed:
            skipped.append(SkippedFile(path=rel, reason=reason))

    for path, rel, dir_reason in _walk(root, ignores):
        if dir_reason is not None:
            skip(rel + "/", dir_reason)
            continue
        if ignores.ignored(rel, is_dir=False):
            skip(rel, "gitignore")
            continue
        result = _classify(path, rel, limits)
        if isinstance(result, str):
            skip(rel, result)
            continue
        language, size, lines = result
        files.append(ScannedFile(path=rel, language=language, size=size, lines=lines))
        if len(files) >= limits.max_files:
            break

    stats: dict[str, LanguageStat] = {}
    for f in files:
        st = stats.setdefault(f.language, LanguageStat())
        st.files += 1
        st.lines += f.lines
    frameworks, manifests, hints = _manifest_info(root, files)
    return ScanResult(
        root=str(root),
        files=files,
        skipped=skipped,
        skipped_counts=dict(counts),
        languages=stats,
        frameworks=frameworks,
        manifests=manifests,
        entry_hints=hints,
        readme_excerpt=_readme_excerpt(root, files, limits.readme_chars),
        tree=build_tree([f.path for f in files], limits.tree_max_lines),
    )
